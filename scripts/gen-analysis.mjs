// Generates the LectureAnalysis types and a precompiled (standalone) Ajv validator from the
// backend's JSON Schema. The /analysis response and TranscriptOut.transcript are typed only by
// this schema, so everything the UI renders from them goes through these validators first.
import { copyFile, writeFile } from "node:fs/promises";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const source = process.env.STAFFROOM_ANALYSIS_SCHEMA ?? "/opt/staffroom1/schema/lecture_analysis.schema.json";
const snapshot = new URL("../schema/lecture_analysis.schema.json", import.meta.url);
try {
  await copyFile(source, snapshot);
  console.log(`analysis: copied ${source}`);
} catch {
  console.warn(`analysis: ${source} not readable; using schema/lecture_analysis.schema.json`);
}
const { default: schema } = await import(snapshot.href, { with: { type: "json" } });

const banner = "/* Generated by scripts/gen-analysis.mjs from lecture_analysis.schema.json. Do not edit. */";
// Property-level titles make json-schema-to-typescript emit one alias per field (Quote1,
// EndMs2, ...). Keep only the $defs titles, which name the real types.
function stripPropertyTitles(node, isDef = false) {
  if (Array.isArray(node)) return node.map((n) => stripPropertyTitles(n));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && !isDef) continue; // the annotation keyword, not a property called "title"
    if (k === "$defs") out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, stripPropertyTitles(d, true)]));
    else if (k === "properties") out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, stripPropertyTitles(d)]));
    else out[k] = stripPropertyTitles(v);
  }
  return out;
}
const tsSchema = stripPropertyTitles(structuredClone(schema));
tsSchema.title = "LectureAnalysis";
const ts = await compile(tsSchema, "LectureAnalysis", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  enableConstEnums: false,
  inferStringEnumKeysFromValues: false,
  format: true,
});
await writeFile(new URL("../src/analysis/types.gen.ts", import.meta.url), ts);

// strict: unknown keywords are errors, so a schema change can't silently weaken validation.
// strictTypes is off only because the backend's discriminator sits beside oneOf without a
// redundant `type: "object"`; the discriminated branches are themselves typed objects.
// `discriminator` is an OpenAPI annotation, not a JSON Schema keyword. Ajv's version would also
// demand that `kind` be required, which is stricter than the backend's schema. Validate with
// plain JSON Schema semantics instead: the oneOf branches are already exclusive by `kind` const.
function dropDiscriminator(node) {
  if (Array.isArray(node)) return node.map(dropDiscriminator);
  if (node === null || typeof node !== "object") return node;
  return Object.fromEntries(Object.entries(node).filter(([k]) => k !== "discriminator").map(([k, v]) => [k, dropDiscriminator(v)]));
}
const ajvSchema = dropDiscriminator(structuredClone(schema));
const ajv = new Ajv({ strict: true, allErrors: false, code: { source: true, esm: true }, schemas: [{ ...ajvSchema, $id: "lecture_analysis" }] });
addFormats(ajv, ["date-time", "date"]);
let code = standaloneCode(ajv, {
  validateLectureAnalysis: "lecture_analysis",
  validateTranscript: "lecture_analysis#/$defs/Transcript",
});
// Ajv's ESM output still require()s the format checkers; browsers need an import.
const formatsRequire = 'require("ajv-formats/dist/formats").fullFormats';
if (code.includes("require(") && !code.replaceAll(formatsRequire, "").includes("require(")) {
  code = 'import { fullFormats } from "ajv-formats/dist/formats.js";\n' + code.replaceAll(formatsRequire, "fullFormats");
} else if (code.includes("require(")) {
  throw new Error("validate.gen.js has an unexpected require(); extend the rewrite in gen-analysis.mjs");
}
await writeFile(new URL("../src/analysis/validate.gen.js", import.meta.url), banner + "\n// @ts-nocheck\n" + code);
await writeFile(
  new URL("../src/analysis/validate.gen.d.ts", import.meta.url),
  `${banner}
import type { ErrorObject } from "ajv";
export interface StandaloneValidator { (data: unknown): boolean; errors?: ErrorObject[] | null }
export declare const validateLectureAnalysis: StandaloneValidator;
export declare const validateTranscript: StandaloneValidator;
`,
);
console.log("analysis: wrote types.gen.ts, validate.gen.js");
