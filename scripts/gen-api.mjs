// Generates src/api/schema.gen.ts from the running API's OpenAPI document and keeps a snapshot
// in schema/openapi.json so builds and reviews don't depend on the API being up.
import { writeFile, readFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const url = process.env.STAFFROOM_OPENAPI_URL ?? "http://127.0.0.1:8000/openapi.json";
const snapshot = new URL("../schema/openapi.json", import.meta.url);

let doc;
try {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  doc = await res.json();
  await writeFile(snapshot, JSON.stringify(doc, null, 2) + "\n");
  console.log(`openapi: fetched ${url}`);
} catch (err) {
  console.warn(`openapi: could not fetch ${url} (${err.message}); using schema/openapi.json`);
  doc = JSON.parse(await readFile(snapshot, "utf8"));
}

const ast = await openapiTS(doc, { alphabetize: false, rootTypes: false });
const banner = "// Generated by scripts/gen-api.mjs from the API's /openapi.json. Do not edit.\n";
await writeFile(new URL("../src/api/schema.gen.ts", import.meta.url), banner + astToString(ast));
console.log("openapi: wrote src/api/schema.gen.ts");
