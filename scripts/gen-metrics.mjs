// Generates src/metrics/definitions.gen.ts from the backend's docs/metrics.md (itself generated
// from the metric registry), so help text in lists matches the analysis' own definitions.
import { readFile, writeFile, copyFile } from "node:fs/promises";

const source = process.env.STAFFROOM_METRICS_MD ?? "/opt/staffroom1/docs/metrics.md";
const snapshot = new URL("../schema/metrics.md", import.meta.url);
try {
  await copyFile(source, snapshot);
} catch {
  console.warn(`metrics: ${source} not readable; using schema/metrics.md`);
}
const md = await readFile(snapshot, "utf8");
const out = {};
for (const block of md.split(/^## /m).slice(1)) {
  const name = block.match(/^`([a-z0-9_]+)`/)?.[1];
  if (!name) continue;
  const body = block.split("\n").slice(1);
  const definition = body.filter((l) => l.trim() && !l.startsWith("- ")).join(" ").trim();
  const unit = body.find((l) => l.startsWith("- Unit:"))?.slice(7).trim() ?? "";
  const dataSource = body.find((l) => l.startsWith("- Data source:"))?.slice(14).trim() ?? "";
  out[name] = { definition, unit, dataSource };
}
const ts = `// Generated by scripts/gen-metrics.mjs from docs/metrics.md. Do not edit.
export interface MetricDefinition { readonly definition: string; readonly unit: string; readonly dataSource: string }
export const METRIC_DEFINITIONS: Readonly<Record<string, MetricDefinition>> = ${JSON.stringify(out, null, 2)};
`;
await writeFile(new URL("../src/metrics/definitions.gen.ts", import.meta.url), ts);
console.log(`metrics: wrote ${Object.keys(out).length} definitions`);
